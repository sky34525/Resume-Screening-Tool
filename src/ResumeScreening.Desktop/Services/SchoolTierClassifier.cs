    // 排名兜底值：985=110, 211=130, 普通=200, 未知=300
    private const int RankFallback985 = 110;
    private const int RankFallback211 = 130;
    private const int RankFallbackNormal = 200;
    private const int RankUnknown = 300;

    /// <summary>
    /// 获取学校排名。数字越小越靠前。若无法识别则返回 300。
    /// </summary>
    public static int GetRank(string? schoolName)
    {
        if (string.IsNullOrWhiteSpace(schoolName))
        {
            return RankUnknown;
        }

        var normalized = schoolName.Trim();

        // 1. 精确匹配软科排名
        if (SoftKeRanking.TryGetValue(normalized, out var rank))
        {
            return rank;
        }

        // 2. 包含匹配（处理"哈尔滨工业大学（威海）"等变体）
        foreach (var (key, value) in SoftKeRanking)
        {
            if (normalized.Contains(key, StringComparison.OrdinalIgnoreCase))
            {
                return value;
            }
        }

        // 3. 兜底：985
        foreach (var school in Fallback985)
        {
            if (normalized.Contains(school, StringComparison.OrdinalIgnoreCase))
            {
                return RankFallback985;
            }
        }

        // 4. 兜底：211
        foreach (var school in Fallback211)
        {
            if (normalized.Contains(school, StringComparison.OrdinalIgnoreCase))
            {
                return RankFallback211;
            }
        }

        return RankUnknown;
    }

    /// <summary>
    /// 获取学校排名标签，用于界面展示。
    /// </summary>
    public static string GetTierLabel(string? schoolName)
    {
        var rank = GetRank(schoolName);
        return rank switch
        {
            <= 10 => $"Top 10 (#{rank})",
            <= 50 => $"Top 50 (#{rank})",
            <= 100 => $"Top 100 (#{rank})",
            <= 110 => "985",
            <= 130 => "211",
            <= 200 => "普通院校",
            _ => "未知"
        };
    }
